export const SECTION_IDS = Object.keys(SECTIONS);

// ---------------------------------------------------------------------------
// Field helpers
// ---------------------------------------------------------------------------
const visible = (f) => !f.internal;

export function fieldsOf(sectionId, { translatableOnly = false, json = null } = {}) {
  const section = SECTIONS[sectionId];
  if (!section) throw new Error(`Unknown section "${sectionId}"`);
  return section.fields.filter((f) => {
    if (!visible(f)) return false;
    if (translatableOnly && !f.translatable) return false;
    if (json === true && f.type !== "json") return false;
    if (json === false && f.type === "json") return false;
    return true;
  });
}

export function slugify(text) {
  return String(text ?? "")
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60);
}

export const isHttpUrl = (v) => /^https?:\/\/[^\s]+$/i.test(v);
export const isSafeImage = (v) => isHttpUrl(v) || (/^\/[^\s]*$/.test(v) && !v.includes(".."));

// ---------------------------------------------------------------------------
// Project detail page (JSON blocks) - structural validation
// ---------------------------------------------------------------------------
const isObj = (v) => v !== null && typeof v === "object" && !Array.isArray(v);
const isStr = (v) => typeof v === "string" && v.trim().length > 0;

// type -> keys that must be arrays when present
const BLOCK_ARRAYS = {
  textCard: ["paragraphs"],
  listCard: ["items"],
  sectionsCard: ["sections"],
  gridCards: ["items"],
  highlightBoxes: ["items"],
  dataTable: ["headers", "rows"],
  teamGrid: ["members"],
  workflowExplorer: [],
};
const SIDEBAR_TYPES = new Set(["techStack", "infoList", "statCard", "chipStack"]);
export const DETAIL_BLOCK_TYPES = Object.keys(BLOCK_ARRAYS);

export function validateProjectDetail(d) {
  const errors = [];
  if (!isObj(d)) return ["The details page must be a JSON object."];
  const m = d.meta;
  if (!isObj(m) || !isStr(m.title) || !isStr(m.subtitle) || !Array.isArray(m.tabs) || m.tabs.length < 1 || m.tabs.length > 8 || !m.tabs.every(isStr)) {
    errors.push("meta needs a title, a subtitle and 1-8 tab names.");
  }
  if (!Array.isArray(d.tabsContent) || (Array.isArray(m?.tabs) && d.tabsContent.length !== m.tabs.length)) {
    errors.push("tabsContent must hold one list of blocks per tab.");
  } else {
    d.tabsContent.forEach((blocks, i) => {
      if (!Array.isArray(blocks)) return errors.push(`Tab ${i + 1} must be a list of blocks.`);
      blocks.forEach((b, j) => {
        const at = `Tab ${i + 1}, block ${j + 1}`;
        if (!isObj(b) || !(b.type in BLOCK_ARRAYS)) return errors.push(`${at}: unknown block type "${b?.type}".`);
        for (const key of BLOCK_ARRAYS[b.type]) {
          if (b[key] !== undefined && !Array.isArray(b[key])) errors.push(`${at}: "${key}" must be a list.`);
        }
        if (b.type === "dataTable" && Array.isArray(b.rows) && !b.rows.every(Array.isArray)) errors.push(`${at}: every table row must be a list of cells.`);
      });
    });
  }
  if (d.sidebar !== undefined) {
    if (!Array.isArray(d.sidebar)) errors.push("sidebar must be a list.");
    else d.sidebar.forEach((b, i) => { if (!isObj(b) || !SIDEBAR_TYPES.has(b.type)) errors.push(`Sidebar item ${i + 1}: unknown type "${b?.type}".`); });
  }
  if (d.techStack !== undefined && !Array.isArray(d.techStack)) errors.push("techStack must be a list.");
  return errors;
}

// A translated detail page must keep the same skeleton as the source.
export function sameDetailShape(a, b) {
  const shape = (x) =>
    Array.isArray(x) ? `[${x.map(shape).join(",")}]`
    : isObj(x) ? `{${Object.keys(x).sort().map((k) => `${k}:${shape(x[k])}`).join(",")}}`
    : typeof x;
  return shape(a) === shape(b);
}

