// ---------------------------------------------------------------------------
// JSON Schemas for Claude structured outputs.
// Structured outputs require additionalProperties:false on every object and do
// not allow free-form objects, so JSON-typed fields travel as JSON-encoded strings.
// ---------------------------------------------------------------------------
function fieldSchema(f) {
  const description = [f.label, f.help].filter(Boolean).join(". ");
  switch (f.type) {
    case "list":
      return { type: "array", items: { type: "string" }, description };
    case "tags":
      return { type: "array", items: { type: "string", enum: f.options }, description };
    case "json":
      return { type: "string", description: `${description}. A JSON document encoded as a string. Use "" if not applicable.` };
    default:
      return { type: "string", description: `${description}. Use "" if unknown.` };
  }
}

function objectSchema(fields) {
  return {
    type: "object",
    additionalProperties: false,
    required: fields.map((f) => f.key),
    properties: Object.fromEntries(fields.map((f) => [f.key, fieldSchema(f)])),
  };
}

// scope: "fields" (everything except JSON fields) | "detail" (only JSON fields)
export function buildGenerateSchema(sectionId, scope) {
  const fields = fieldsOf(sectionId, { json: scope === "detail" });
  const props = { fields: objectSchema(fields), notes: { type: "string", description: "Short note for the owner: assumptions made, missing information, things to double-check. Use \"\" if none." } };
  const required = ["fields", "notes"];
  if (scope === "fields") {
    props.slug = { type: "string", description: "Short lowercase URL-safe identifier using only a-z, 0-9 and hyphens." };
    required.unshift("slug");
  }
  return { type: "object", additionalProperties: false, required, properties: props };
}

export function buildTranslateSchema(sectionId, scope) {
  const fields = fieldsOf(sectionId, { translatableOnly: true, json: scope === "detail" });
  return {
    type: "object",
    additionalProperties: false,
    required: ["fields", "notes"],
    properties: {
      fields: objectSchema(fields),
      notes: { type: "string", description: "Short note about translation choices or terms left in English. Use \"\" if none." },
    },
  };
}

// ---------------------------------------------------------------------------
// Normalising + validating data (used on Claude output AND on editor saves)
// ---------------------------------------------------------------------------
const clean = (s) => String(s ?? "").replace(/\r\n/g, "\n").trim();

// Turn raw field values (possibly Claude output with JSON as strings) into data.
export function normalizeFields(sectionId, raw, { translatableOnly = false, json = null } = {}) {
  const out = {};
  const problems = [];
  for (const f of fieldsOf(sectionId, { translatableOnly, json })) {
    let v = raw?.[f.key];
    if (v === undefined || v === null) continue;
    switch (f.type) {
      case "list":
        v = (Array.isArray(v) ? v : String(v).split("\n")).map(clean).filter(Boolean);
        if (v.length) out[f.key] = v;
        break;
      case "tags":
        v = (Array.isArray(v) ? v : []).filter((t) => f.options.includes(t));
        if (v.length) out[f.key] = [...new Set(v)];
        break;
      case "json": {
        if (typeof v === "string") {
          if (!clean(v)) break;
          try { v = JSON.parse(v); } catch { problems.push(`${f.label} is not valid JSON.`); break; }
        }
        if (isObj(v)) out[f.key] = v;
        break;
      }
      default:
        v = clean(v);
        if (v) out[f.key] = v;
    }
  }
  return { data: out, problems };
}

// Validate a complete item (canonical English data). Returns a list of messages.
export function validateItemData(sectionId, data) {
  const errors = [];
  for (const f of fieldsOf(sectionId)) {
    const v = data?.[f.key];
    const empty = v === undefined || v === null || v === "" || (Array.isArray(v) && v.length === 0);
    if (f.required && empty) { errors.push(`${f.label} is required.`); continue; }
    if (empty) continue;
    if (f.pattern && !new RegExp(f.pattern).test(String(v))) errors.push(`${f.label} has an invalid format.`);
    if (f.type === "url" && !isHttpUrl(String(v))) errors.push(`${f.label} must start with http:// or https://.`);
    if (f.type === "image" && !isSafeImage(String(v))) errors.push(`${f.label} must be an http(s) URL or a site path starting with "/".`);
    if (f.type === "json" && f.kind === "projectDetail") errors.push(...validateProjectDetail(v));
  }
  return errors;
}

// Merge the canonical data with one language's overrides (client + server).
export function localizeData(data, translations, lang) {
  const overrides = lang && lang !== "en" ? translations?.[lang] : null;
  return overrides ? { ...data, ...overrides } : data;
}
